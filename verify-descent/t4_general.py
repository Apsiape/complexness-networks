def predict_general(S, x):
    """rho_out = 2^{|W|} 2^{-H} SUM_{c: supp(c) subset U u V}
                  s_c (-1)^{|D_c|} h_c  J_{R_c} (x) TENSOR_j alpha_j(c)
       alpha_j = Omega_j (no holder of pair j in D)
               = -Omega_j (both holders in D)
               = (1/4)(J_a + J_a')  (exactly one, the one in D having aux site a)"""
    tot = Sym()
    for w, bits, s in S.words:
        D = frozenset(w) & frozenset(S.U)
        R = frozenset(w) - frozenset(S.U)
        if R & frozenset(S.W):
            continue                       # not covered -> dies in the trace
        h = 1.0
        for u in D: h *= x[u]
        term = Sym({frozenset(R): s * ((-1.0) ** len(D)) * h})
        for (u, v) in S.auxpairs:
            a, b = S.aux[u], S.aux[v]
            inD = [q for q in (u, v) if q in D]
            Om = sym_add(sym_scale(sym_I(), 0.25), sym_scale(sym_J([a, b]), -0.25))
            if len(inD) == 2:
                aj = sym_scale(Om, -1.0)
            elif len(inD) == 0:
                aj = Om
            else:
                aa = S.aux[inD[0]]
                aj = sym_scale(sym_add(sym_J([a]), sym_J([b])), 0.25) if aa == a else \
                     sym_scale(sym_add(sym_J([b]), sym_J([a])), 0.25)
                # J_{aa} . Omega_j = (1/4)(J_a + J_b) either way -- verify below
            term = sym_mul(term, aj)
        tot = sym_add(tot, term)
    return sym_scale(tot, (2.0 ** len(S.W)) * (2.0 ** (-S.H)))


def structure_flags(S, x):
    """H2 = every covered codeword's measured support is a union of aux pairs
       H3 = the R-image code is generated by pairwise-disjoint weight-2 words"""
    H2 = True
    Rs = set()
    for w, bits, s in S.words:
        D = frozenset(w) & frozenset(S.U)
        R = frozenset(w) - frozenset(S.U)
        if R & frozenset(S.W):
            continue
        for (u, v) in S.auxpairs:
            if ((u in D) + (v in D)) == 1: H2 = False
        Rs.add(frozenset(R))
    H3, why = is_disjoint_pair_generated(Rs)
    return H2, H3, why, Rs


def omega_product_after_flips(S, out):
    """try to reach TENSOR Omega over pair blocks by single-rebit reflections."""
    nrm = normalise(out, len(S.keep))
    if nrm is None: return None
    auxs = set(S.aux.values())
    Vpart = set(frozenset(k - auxs) for k in support_group(nrm))
    ok, why = is_disjoint_pair_generated(Vpart)
    if not ok: return False
    blocks = [frozenset(b) for b in Vpart if len(b) == 2]
    blocks += [frozenset([S.aux[u], S.aux[v]]) for u, v in S.auxpairs]
    cur = nrm
    for b in blocks:
        if cur.get(b, 0.0) * 2.0 ** len(S.keep) > 0.5:
            cur = Sym({T: (-v if sorted(b)[0] in T else v) for T, v in cur.items()})
    tgt = Sym({frozenset(): 2.0 ** (-len(S.keep))})
    for b in blocks:
        tgt = sym_mul(tgt, sym_add(sym_I(), sym_scale(sym_J(b), -1.0)))
    return not sym_add(tgt, sym_scale(cur, -1.0))


