holders = list(range(H))

stats = dict(n=0, formula_bad=0, prod=0, noprod=0, zerobranch=0)
table = {}
cases_examined = []
# all even-weight second generators
for r in (2, 4, 6):
    for c2 in itertools.combinations(holders, r):
        c2 = frozenset(c2)
        if c2 in (frozenset(), c1): continue
        for q2 in (0, 1):
            S = Setup(H=H, auxpairs=auxpairs, gens=[sorted(c1), sorted(c2)], qvals=[0, q2])
            H2, H3, why, Rs = structure_flags(S, {u: 1 for u in S.U})
            allbr_prod = True
            formula_ok = True
            zero = 0
            for bvals in itertools.product([1, -1], repeat=len(S.U)):
                xx = dict(zip(S.U, bvals))
                pB, outB = engineB(S, xx)
                pg = predict_general(S, xx)
                if sym_add(outB, sym_scale(pg, -1.0)): formula_ok = False
                if abs(pB) < 1e-13:
                    zero += 1; continue
                if omega_product_after_flips(S, outB) is not True: allbr_prod = False
            stats['n'] += 1
            if not formula_ok: stats['formula_bad'] += 1
            if zero: stats['zerobranch'] += 1
            key = (H2, H3, allbr_prod)
            table[key] = table.get(key, 0) + 1
            if allbr_prod: stats['prod'] += 1
            else: stats['noprod'] += 1
            cases_examined.append((sorted(c2), q2, H2, H3, allbr_prod, zero, why))

